function source(pages: string): string {
  return PDF_TITLE + "第 " + pages + " 頁";
}

function activity(
  name: string,
  description: string,
  period: ActivityPeriod,
  destinationId: string | undefined,
  mapsQuery: string | undefined,
  status: Status,
  sourceReference: string,
): Activity {
  const mapsCoordinates = mapsQuery ? activityMapCoordinates[mapsQuery] : undefined;
  const approvedMapsUrl = mapsQuery
    ? (ACTIVITY_GOOGLE_MAPS_URLS as Readonly<Record<string, string>>)[mapsQuery]
    : undefined;
  const approvedMapsLinks = mapsQuery
    ? (ACTIVITY_GOOGLE_MAPS_LINKS as Readonly<Record<string, readonly { label: string; url: string }[]>>)[mapsQuery]
    : undefined;

  if (mapsQuery && !mapsCoordinates) {
    throw new Error("Missing verified coordinates for activity map: " + mapsQuery);
  }

  return {
    name,
    description,
    period,
    destinationId,
    mapsQuery,
    mapsCoordinates,
    mapsUrl: approvedMapsUrl ?? (mapsQuery && mapsCoordinates
      ? createGoogleMapsUrl(mapsQuery, mapsCoordinates)
      : undefined),
    mapsLinks: approvedMapsLinks,
    status,
    sourceReference,
  };
}

function meals(
  breakfast: string,
  lunch: string,
  dinner: string,
  sourceReference: string,
): MealInfo {
  return {
    breakfast,
    lunch,
    dinner,
    sourceReference,
    status: "confirmed",
    lastReviewedAt: LAST_REVIEWED_AT,
  };
}

function accommodation(
  name: string,
  cityOrRegion: string,
  address: string,
  sourceReference: string,
  note?: string,
  mapsUrl?: string,
): Accommodation {
  return {
    name,
    cityOrRegion,
    notes: [address, note].filter(Boolean).join("；"),
    mapsUrl,
    status: "confirmed",
    sourceReference,
  };
}

function transport(
  type: string,
  route: string,
  description: string,
  sourceReference: string,
  extra: Partial<Transport> = {},
): Transport {
  return {
    type,
    route,
    description,
    status: "confirmed",
    sourceReference,
    ...extra,
  };
}

